#!/usr/bin/env python3
"""Regenerate the Subcarchy inventory from a running Omarchy system.

Reads the packaged Omarchy tree, the pacman database and the user's
Omarchy configuration, then writes Markdown tables under
docs/inventory/generated/. It never prints configuration values; it records
names, versions, origins and counts only.

Usage: python3 tools/inventory/collect.py [--out DIR] [--home DIR]
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import socket
import subprocess
from collections import Counter, defaultdict
from pathlib import Path

OMARCHY = Path(os.environ.get("OMARCHY_PATH", "/usr/share/omarchy"))
REPO = Path(__file__).resolve().parents[2]
# Plugin id prefixes that belong to the owner rather than the community.
OWN_PREFIXES = ("onnwee.", "patrickfanella.", "io.github.patrickfanella.")
RICE_PREFIX = "subcult."


def run(*cmd: str) -> str:
    try:
        return subprocess.run(cmd, capture_output=True, text=True, check=False).stdout
    except FileNotFoundError:
        return ""


def cell(value: object) -> str:
    text = "" if value is None else str(value)
    return text.replace("|", "\\|").replace("\n", " ").strip()


def table(headers: list[str], rows: list[list[object]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(cell(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def clean_url(url: str) -> str:
    return re.sub(r"://[^@/]+@", "://", url.strip())


def git_origin(path: Path) -> str:
    if not (path / ".git").exists():
        return ""
    url = run("git", "-C", str(path), "remote", "get-url", "origin")
    return clean_url(url) if url else ""


def read_json(path: Path) -> dict:
    try:
        return json.loads(path.read_text())
    except (OSError, ValueError):
        return {}


def header(title: str, source: str) -> str:
    stamp = dt.date.today().isoformat()
    return (
        f"# {title}\n\n"
        f"> Generated by `tools/inventory/collect.py` on `{socket.gethostname()}` at {stamp}.\n"
        f"> Source: {source}. Do not edit by hand; rerun the script.\n"
    )


# --------------------------------------------------------------------------
# pacman data


def pacman_local() -> dict[str, dict]:
    pkgs = {}
    for line in run("expac", "-Q", "%n\t%v\t%d\t%w").splitlines():
        name, ver, desc, reason = (line.split("\t") + ["", "", "", ""])[:4]
        pkgs[name] = {"version": ver, "desc": desc, "explicit": reason == "explicit"}
    return pkgs


def pacman_repos() -> dict[str, str]:
    repos = {}
    for line in run("expac", "-S", "%r\t%n").splitlines():
        repo, _, name = line.partition("\t")
        repos.setdefault(name, repo)
    return repos


def package_list(path: Path) -> list[str]:
    names = []
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            names.append(line)
    return names


# --------------------------------------------------------------------------
# upstream Omarchy


def upstream_packages(local: dict, repos: dict) -> str:
    out = [header("Omarchy package lists", f"`{OMARCHY}/install/*.packages`, pacman database")]
    lists = sorted((OMARCHY / "install").glob("*.packages"))
    summary = []
    for path in lists:
        names = package_list(path)
        installed = sum(1 for n in names if n in local)
        summary.append([f"`{path.name}`", len(names), installed])
    out.append("## Lists\n\n" + table(["List", "Packages", "Installed here"], summary))
    out.append(
        "`omarchy-base` is what the ISO pacstraps. `omarchy-other` covers optional "
        "installers and hardware fixes. The aarch64 lists are platform-specific."
    )
    for path in lists:
        rows = []
        for name in package_list(path):
            info = local.get(name)
            rows.append([
                f"`{name}`",
                repos.get(name, "?" if not info else "local/AUR"),
                info["version"] if info else "not installed",
                info["desc"] if info else "",
            ])
        out.append(f"## {path.name}\n\n" + table(["Package", "Repo", "Installed", "Description"], rows))
    return "\n\n".join(out) + "\n"


def omarchy_repo_packages(local: dict, repos: dict) -> str:
    out = [header("Packages from the Omarchy repository", "`pacman -Sl omarchy`, pacman database")]
    names = sorted(n for n, r in repos.items() if r == "omarchy")
    rows = []
    for name in names:
        info = local.get(name)
        rows.append([f"`{name}`", info["version"] if info else "not installed", info["desc"] if info else ""])
    out.append(
        f"The `[omarchy]` pacman repository (https://pkgs.omarchy.org) carries {len(names)} packages. "
        "Packages named `omarchy-*` and `linux-omarchy*` are Omarchy's own; the rest are rebuilt "
        "or AUR packages it mirrors so installs need no AUR helper."
    )
    out.append(table(["Package", "Installed", "Description"], rows))
    return "\n\n".join(out) + "\n"


def upstream_commands() -> str:
    data = json.loads(run("omarchy", "commands", "--json", "--all") or '{"commands": []}')
    cmds = data.get("commands", [])
    groups: dict[str, list] = defaultdict(list)
    for c in cmds:
        groups[c.get("group") or "(none)"].append(c)
    out = [header("Omarchy commands", "`omarchy commands --json --all`")]
    hidden = sum(1 for c in cmds if c.get("hidden"))
    out.append(
        f"{len(cmds)} commands in {len(groups)} groups; {hidden} are hidden from `omarchy commands`. "
        "Every command is an `omarchy-*` binary in `/usr/bin`, dispatched by `omarchy <group> <action>`."
    )
    summary = [[f"[`{g}`](#{g})", len(v), sum(1 for c in v if c.get("hidden")),
                sum(1 for c in v if c.get("requires_sudo"))] for g, v in sorted(groups.items())]
    out.append("## Groups\n\n" + table(["Group", "Commands", "Hidden", "Need sudo"], summary))
    for g, v in sorted(groups.items()):
        rows = [[f"`{c.get('route', '')}`", c.get("summary", ""), "yes" if c.get("hidden") else "",
                 "yes" if c.get("requires_sudo") else ""] for c in sorted(v, key=lambda c: c.get("route", ""))]
        out.append(f"## {g}\n\n" + table(["Route", "Summary", "Hidden", "Sudo"], rows))
    return "\n\n".join(out) + "\n"


def manifests(root: Path) -> list[tuple[Path, dict]]:
    found = []
    for mf in sorted(root.rglob("manifest.json")):
        data = read_json(mf)
        if data.get("id"):
            found.append((mf.parent, data))
    return found


def upstream_shell() -> str:
    out = [header("Omarchy shell and plugins", f"`{OMARCHY}/shell`")]
    shell = OMARCHY / "shell"
    counts = [[f"`{d.name}/`", sum(1 for f in d.rglob("*") if f.is_file())]
              for d in sorted(shell.iterdir()) if d.is_dir()]
    out.append(
        "The Omarchy shell is a Quickshell (QML) program started by `shell.qml`. It draws the bar, "
        "menus, notifications, OSD, lock screen, dock and panels. Each feature is a plugin with a "
        "`manifest.json`.\n\n" + table(["Directory", "Files"], counts)
    )
    rows = []
    for path, m in manifests(shell / "plugins"):
        rows.append([f"`{m['id']}`", m.get("name", ""), ", ".join(m.get("kinds", [])),
                     f"`{path.relative_to(shell)}`", m.get("description", "")])
    out.append(f"## Built-in plugins ({len(rows)})\n\n" + table(["ID", "Name", "Kinds", "Path", "Description"], rows))
    return "\n\n".join(out) + "\n"


def upstream_themes() -> str:
    out = [header("Omarchy stock themes", f"`{OMARCHY}/themes`")]
    rows = []
    for d in sorted((OMARCHY / "themes").iterdir()):
        if not d.is_dir():
            continue
        files = sorted(f.name for f in d.iterdir() if f.is_file())
        bgs = d / "backgrounds"
        nbg = sum(1 for _ in bgs.iterdir()) if bgs.is_dir() else 0
        light = "yes" if (d / "light.mode").exists() else ""
        rows.append([f"`{d.name}`", nbg, light, ", ".join(files)])
    out.append(f"{len(rows)} themes. A theme is a directory of per-app colour files plus backgrounds.")
    out.append(table(["Theme", "Backgrounds", "Light", "Files"], rows))
    return "\n\n".join(out) + "\n"


def tree_counts(root: Path, depth: int = 1) -> list[list[object]]:
    rows = []
    for d in sorted(root.iterdir()):
        n = sum(1 for f in d.rglob("*") if f.is_file()) if d.is_dir() else 1
        rows.append([f"`{d.relative_to(OMARCHY)}{'/' if d.is_dir() else ''}`", n])
        if depth > 1 and d.is_dir():
            for sub in sorted(d.iterdir()):
                if sub.is_dir():
                    m = sum(1 for f in sub.rglob("*") if f.is_file())
                    rows.append([f"`{sub.relative_to(OMARCHY)}/`", m])
    return rows


def upstream_layout() -> str:
    out = [header("Omarchy source layout", f"`{OMARCHY}`")]
    version = (OMARCHY / "version").read_text().strip() if (OMARCHY / "version").exists() else "?"
    out.append(f"Installed Omarchy version: `{version}`.")
    out.append("## Top level\n\n" + table(["Path", "Files"], tree_counts(OMARCHY)))
    for name in ("config", "default", "install"):
        out.append(f"## {name}/\n\n" + table(["Path", "Files"], tree_counts(OMARCHY / name)))
    apps = sorted(p.stem for p in (OMARCHY / "applications").glob("*.desktop"))
    out.append("## applications/ (default desktop entries and web apps)\n\n" + ", ".join(f"`{a}`" for a in apps))
    scripts = sorted(str(p.relative_to(OMARCHY)) for p in (OMARCHY / "install").rglob("*.sh"))
    out.append(f"## Install scripts ({len(scripts)})\n\n" + "\n".join(f"- `{s}`" for s in scripts))
    migs = sorted(p.name for p in (OMARCHY / "migrations").iterdir())
    if migs:
        out.append(f"## migrations/\n\n{len(migs)} migration files, `{migs[0]}` to `{migs[-1]}`. "
                   "File names are Unix timestamps; `omarchy migrate` runs those not yet applied.")
    over = sorted(p.name for p in (OMARCHY / "etc-overrides").iterdir())
    out.append("## etc-overrides/\n\n" + ", ".join(f"`{o}`" for o in over))
    return "\n\n".join(out) + "\n"


