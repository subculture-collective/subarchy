// Package idle turns the user's idle settings (~/.config/subcult/idle.json,
// the settings panel's Idle group) into a hypridle configuration (ADR 0036):
// lock, display off and suspend after so many minutes, 0 for never.
package idle

import (
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"strings"
)

// Settings are the minutes until each step; 0 disables it.
type Settings struct {
	LockAfterMinutes       int `json:"lockAfterMinutes"`
	DisplayOffAfterMinutes int `json:"displayOffAfterMinutes"`
	SuspendAfterMinutes    int `json:"suspendAfterMinutes"`
}

// Defaults: lock before the display goes off, suspend later (ADR 0036).
func Defaults() Settings {
	return Settings{LockAfterMinutes: 7, DisplayOffAfterMinutes: 10, SuspendAfterMinutes: 15}
}

// Load reads idle.json over the defaults. A missing file is the defaults;
// a broken one is an error.
func Load(path string) (Settings, error) {
	s := Defaults()
	b, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return s, nil
	}
	if err != nil {
		return s, err
	}
	if err := json.Unmarshal(b, &s); err != nil {
		return Defaults(), fmt.Errorf("%s: %w", path, err)
	}
	for _, v := range []int{s.LockAfterMinutes, s.DisplayOffAfterMinutes, s.SuspendAfterMinutes} {
		if v < 0 || v > 1440 {
			return Defaults(), fmt.Errorf("%s: minutes out of range", path)
		}
	}
	return s, nil
}

// Render is the hypridle configuration for the settings. The lock goes
// through logind (`loginctl lock-session`), which hypridle answers with
// lock_cmd, so a lock asked for by anything else takes the same path.
func Render(s Settings) string {
	var b strings.Builder
	b.WriteString("# Generated by `subcult idle` from ~/.config/subcult/idle.json (ADR 0036).\n")
	b.WriteString("# Edit the settings, not this file.\n\n")
	b.WriteString("general {\n")
	b.WriteString("    lock_cmd = systemctl --user start subcult-lock.service\n")
	b.WriteString("    before_sleep_cmd = loginctl lock-session\n")
	// Auto inhibition recognizes hyprlock by name; our separate locker needs
	// the explicit lock-notify mode so sleep waits until its surface is ready.
	b.WriteString("    inhibit_sleep = 3\n")
	b.WriteString("    after_sleep_cmd = hyprctl dispatch 'hl.dsp.dpms({ action = \"on\" })'\n")
	b.WriteString("    ignore_dbus_inhibit = false\n")
	b.WriteString("}\n")
	if s.LockAfterMinutes > 0 {
		fmt.Fprintf(&b, "\n# Lock after %d min.\nlistener {\n    timeout = %d\n    on-timeout = loginctl lock-session\n}\n", s.LockAfterMinutes, s.LockAfterMinutes*60)
	}
	if s.DisplayOffAfterMinutes > 0 {
		fmt.Fprintf(&b, "\n# Display off after %d min, back on at the first input.\nlistener {\n    timeout = %d\n", s.DisplayOffAfterMinutes, s.DisplayOffAfterMinutes*60)
		b.WriteString("    on-timeout = hyprctl dispatch 'hl.dsp.dpms({ action = \"off\" })'\n")
		b.WriteString("    on-resume = hyprctl dispatch 'hl.dsp.dpms({ action = \"on\" })'\n}\n")
	}
	if s.SuspendAfterMinutes > 0 {
		fmt.Fprintf(&b, "\n# Suspend after %d min; a keep-awake inhibitor holds this off.\nlistener {\n    timeout = %d\n    on-timeout = systemctl suspend\n}\n", s.SuspendAfterMinutes, s.SuspendAfterMinutes*60)
	}
	return b.String()
}

// Summary is one line for `subcult idle`.
func Summary(s Settings) string {
	part := func(name string, m int) string {
		if m == 0 {
			return name + " never"
		}
		return fmt.Sprintf("%s after %d min", name, m)
	}
	return part("lock", s.LockAfterMinutes) + ", " + part("display off", s.DisplayOffAfterMinutes) + ", " + part("suspend", s.SuspendAfterMinutes)
}
