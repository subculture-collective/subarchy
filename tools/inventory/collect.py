# local additions


def classify_plugin(pid: str, origin: str) -> str:
    if pid.startswith(RICE_PREFIX):
        return "SUBCULT rice"
    if pid.startswith(OWN_PREFIXES) or "patrickfanella" in origin.lower():
        return "own"
    if origin:
        return "community"
    return "local"


def local_plugins(home: Path) -> str:
    cfg = home / ".config/omarchy"
    shell_json = (cfg / "shell.json").read_text() if (cfg / "shell.json").exists() else ""
    shell = read_json(cfg / "shell.json")
    out = [header("Installed shell plugins", "`~/.config/omarchy/plugins/*/manifest.json`, `shell.json`")]
    rows, by_source = [], Counter()
    for d in sorted((cfg / "plugins").iterdir()):
        if not d.is_dir() or d.name.startswith("."):
            continue
        m = read_json(d / "manifest.json")
        pid = m.get("id", d.name)
        origin = git_origin(d)
        source = classify_plugin(pid, origin)
        by_source[source] += 1
        used = "yes" if f'"{pid}"' in shell_json else ""
        cloned = (m.get("omarchy") or {}).get("clonedFrom", "")
        rows.append([f"`{pid}`", m.get("name", ""), m.get("version", ""), source, used,
                     ", ".join(m.get("kinds", [])), cloned, origin, m.get("description", "")])
    out.append(
        f"{len(rows)} plugin directories. "
        + ", ".join(f"{n} {s}" for s, n in sorted(by_source.items()))
        + ". **Referenced** means the id appears in `shell.json` (bar layout, plugin list or settings); "
        "it does not prove the plugin rendered. Source: *own* is Patrick Fanella's, *SUBCULT rice* "
        "comes from `subcult-omarchy-rice`, *community* has a third-party git origin, *local* has none."
    )
    out.append(table(["ID", "Name", "Version", "Source", "Referenced", "Kinds", "Cloned from", "Origin", "Description"], rows))
    disabled = shell.get("disabledPlugins", [])
    out.append("## Disabled built-in plugins\n\n" + (", ".join(f"`{d}`" for d in disabled) or "None."))
    layout = (shell.get("bar") or {}).get("layout", {})
    lrows = [[section, ", ".join(f"`{w.get('id')}`" for w in items if isinstance(w, dict))]
             for section, items in layout.items() if isinstance(items, list) and items]
    out.append(f"## Bar layout (`bar.id` = `{(shell.get('bar') or {}).get('id', 'omarchy.bar')}`)\n\n"
               + table(["Section", "Widgets"], lrows))
    dock = (shell.get("dock") or {}).get("pinned", [])
    out.append("## Dock pins\n\n" + (", ".join(f"`{p}`" for p in dock) or "None."))
    return "\n\n".join(out) + "\n"


def local_themes(home: Path) -> str:
    out = [header("User themes", "`~/.config/omarchy/themes`")]
    rows = []
    for d in sorted((home / ".config/omarchy/themes").iterdir()):
        if not d.is_dir():
            continue
        bgs = d / "backgrounds"
        nbg = sum(1 for _ in bgs.iterdir()) if bgs.is_dir() else 0
        stock = "overlay on stock" if (OMARCHY / "themes" / d.name).exists() else "custom"
        rows.append([f"`{d.name}`", stock, nbg, "yes" if (d / "colors.toml").exists() else "",
                     git_origin(d), sum(1 for f in d.iterdir() if f.is_file())])
    name = run("omarchy", "theme", "current").strip() or "unknown"
    out.append(f"`omarchy theme current` reports `{name}`.")
    out.append(table(["Theme", "Kind", "Backgrounds", "colors.toml", "Origin", "Files"], rows))
    return "\n\n".join(out) + "\n"


def local_hooks_and_extensions(home: Path) -> str:
    cfg = home / ".config/omarchy"
    out = [header("Hooks, menu extensions and Omarchy config files", "`~/.config/omarchy`")]
    rows = []
    for d in sorted((cfg / "hooks").glob("*.d")):
        for f in sorted(d.iterdir()):
            rows.append([f"`{d.name.removesuffix('.d')}`", f"`{f.name}`", "" if f.name.endswith(".sample") else "yes"])
    out.append("## Hooks\n\n`omarchy-hook` runs every non-`.sample` file with `bash`, so the executable bit "
               "does not matter.\n\n" + table(["Event", "Script", "Runs"], rows))
    ext = sorted(f.name for f in (cfg / "extensions").iterdir())
    out.append("## Menu extensions\n\n" + "\n".join(f"- `extensions/{e}`" for e in ext))
    files = sorted(f.name for f in cfg.iterdir() if f.is_file() and ".bak" not in f.name)
    out.append("## Top-level config files\n\nValues are not recorded here.\n\n" + ", ".join(f"`{f}`" for f in files))
    dirs = sorted(f.name for f in cfg.iterdir() if f.is_dir())
    out.append("## Top-level directories\n\n" + ", ".join(f"`{d}/`" for d in dirs))
    hypr = sorted(f.name for f in (home / ".config/hypr").iterdir() if f.is_file() and ".bak" not in f.name
                  and "backup" not in f.name)
    out.append("## Hyprland user files\n\n" + ", ".join(f"`{h}`" for h in hypr))
    return "\n\n".join(out) + "\n"


def local_scripts_and_services(home: Path) -> str:
    out = [header("User scripts and services", "`~/.local/bin`, `~/.config/systemd/user`")]
    groups: dict[str, list] = defaultdict(list)
    for f in sorted((home / ".local/bin").iterdir()):
        if ".bak" in f.name or f.name == "__pycache__":
            continue
        name = f.name
        if f.is_symlink():
            target = os.readlink(f).replace(str(home), "~")
            kind = "mise shim" if "mise/shims" in target else "link"
            groups[kind].append(f"`{name}` → `{target}`")
        elif name.startswith("subcult-"):
            groups["SUBCULT rice"].append(f"`{name}`")
        elif name.startswith(("omarchy-", "sputnik-")) or name in ("hyprctl", "scrolling-view-toggle"):
            groups["desktop overrides and host helpers"].append(f"`{name}`")
        else:
            groups["other"].append(f"`{name}`")
    for kind, items in sorted(groups.items()):
        out.append(f"## ~/.local/bin: {kind} ({len(items)})\n\n" + ", ".join(items))
    units = sorted(f.name for f in (home / ".config/systemd/user").iterdir()
                   if f.is_file() and not f.name.endswith((".wants", ".requires")))
    enabled = set(run("systemctl", "--user", "list-unit-files", "--state=enabled", "--no-legend").split())
    rows = [[f"`{u}`", "yes" if u in enabled else ""] for u in units]
    out.append("## User systemd units in ~/.config/systemd/user\n\n" + table(["Unit", "Enabled"], rows))
    pkg_units = sorted(u for u in enabled if u.endswith((".service", ".timer", ".path", ".socket")) and u not in units)
    out.append("## Other enabled user units (packaged)\n\n" + ", ".join(f"`{u}`" for u in pkg_units))
    apps = sorted(p.name for p in (home / ".local/share/applications").glob("*.desktop"))
    out.append(f"## Desktop entries in ~/.local/share/applications ({len(apps)})\n\n" + ", ".join(f"`{a}`" for a in apps))
    return "\n\n".join(out) + "\n"


def local_packages(local: dict, repos: dict) -> str:
    out = [header("Packages beyond Omarchy", "pacman database compared with Omarchy package lists")]
    listed = set()
    for path in (OMARCHY / "install").glob("*.packages"):
        listed.update(package_list(path))
    deps = {re.split(r"[<>=]", d)[0] for d in run("pactree", "-u", "omarchy").split()}
    extra = sorted(n for n, i in local.items() if i["explicit"] and n not in listed and n not in deps)
    by_repo: dict[str, list] = defaultdict(list)
    for n in extra:
        by_repo[repos.get(n, "foreign (AUR or local build)")].append(n)
    out.append(
        f"{len(extra)} explicitly installed packages are neither in an Omarchy package list nor a "
        "dependency of the `omarchy` package. Some are still installed by Omarchy's optional "
        "`omarchy install` commands; check before treating them as personal additions."
    )
    for repo, names in sorted(by_repo.items()):
        rows = [[f"`{n}`", local[n]["version"], local[n]["desc"]] for n in names]
        out.append(f"## {repo} ({len(names)})\n\n" + table(["Package", "Version", "Description"], rows))
    missing = sorted(n for n in listed if n not in local)
    out.append(f"## Omarchy-listed packages not installed here ({len(missing)})\n\n"
               "Includes other-architecture and optional packages.\n\n" + ", ".join(f"`{m}`" for m in missing))
    mise = run("mise", "ls", "--current")
    rows = []
    for line in mise.splitlines():
        parts = line.split()
        if len(parts) >= 2:
            rows.append([f"`{parts[0]}`", parts[1]])
    out.append(f"## mise tools ({len(rows)})\n\n" + table(["Tool", "Version"], rows))
    return "\n\n".join(out) + "\n"


# Wikilink targets for the closing "Related" line of each generated note.
RELATED = {
    "omarchy": "[[inventory-index|Inventory]] · [[omarchy-overview|Omarchy component map]]",
    "local": "[[inventory-index|Inventory]] · [[local-additions|Local additions]] · [[triage|Triage]]",
}


def with_frontmatter(name: str, text: str) -> str:
    """Prefix Obsidian properties and append a Related line."""
    scope = name.split("-", 1)[0]
    title = text.splitlines()[0].removeprefix("# ").strip()
    source = next((l.split("Source: ", 1)[1].rsplit(". Do not edit", 1)[0]
                   for l in text.splitlines() if l.startswith("> Source: ")), "")
    observed = dt.date.today().isoformat()
    fm = (
        "---\n"
        f"title: {json.dumps(title)}\n"
        "type: inventory\n"
        "status: generated\n"
        f"scope: {scope}\n"
        f"host: {socket.gethostname()}\n"
        f"observed: {observed}\n"
        f"source: {json.dumps(source)}\n"
        f"tags: [inventory, generated, {scope}]\n"
        "---\n\n"
    )
    return fm + text.rstrip("\n") + f"\n\nRelated: {RELATED[scope]}\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=REPO / "docs/inventory/generated")
    ap.add_argument("--home", type=Path, default=Path.home())
    args = ap.parse_args()

    local, repos = pacman_local(), pacman_repos()
    files = {
        "omarchy-layout.md": upstream_layout(),
        "omarchy-commands.md": upstream_commands(),
        "omarchy-packages.md": upstream_packages(local, repos),
        "omarchy-repo-packages.md": omarchy_repo_packages(local, repos),
        "omarchy-shell.md": upstream_shell(),
        "omarchy-themes.md": upstream_themes(),
        "local-plugins.md": local_plugins(args.home),
        "local-themes.md": local_themes(args.home),
        "local-config.md": local_hooks_and_extensions(args.home),
        "local-scripts-and-services.md": local_scripts_and_services(args.home),
        "local-packages.md": local_packages(local, repos),
    }
    args.out.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        path = args.out / name
        path.write_text(with_frontmatter(name, text))
        print(f"wrote {path.relative_to(REPO) if path.is_relative_to(REPO) else path}")

if __name__ == "__main__":
    main()
